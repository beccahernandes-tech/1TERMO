# Para copiar uma linha interia para a próxima, "Alt + Shift + SetaBaixo"
# Para copiar uma linha inteira, mas sem mover o cursor: "Alt + Shift + SetaCima"
# Para realizar multiplas seleções de uma unica palavra: "Crtl + D"

